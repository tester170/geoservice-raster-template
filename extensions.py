# Собственная функция сервиса. Сервис вызывает extension() после классификации области интереса и показывает её результат
# таблицей и кратким выводом. Функция использует только данные, которые сервис уже получил: карты классов области,
# карточку модели и результаты основного расчёта.
#
# Аргументы:
#   maps   – словарь {период: карта классов}; период – год или интервал дат «ГГГГ-ММ-ДД…ГГГГ-ММ-ДД»; карта – массив
#            NumPy в проекции UTM: номер класса 0, 1, 2… в порядке card["classes"], −1 – вне области интереса;
#   card   – карточка модели (классы, класс в фокусе, сезон; в режимах обучения на лету focus – None);
#   result – словарь основного расчёта: "year" – период карты, "areas" – площади классов, км², "pixel_km2" – площадь
#            пикселя, км² (зависит от разрешения); для двух периодов – "compare_year", "net_change", "matrix".
# Возвращает словарь: {"name": "Название функции", "table": список строк-словарей или None, "text": "краткий вывод" или None}
import numpy as np

NAME = "Пример: доли классов области"  # Заголовок результата.


def extension(maps, card, result):
    """Пример: доля каждого класса в площади области интереса. Замените своей функцией."""
    classes = maps[result["year"]]  # Карта основного периода.
    inside = classes[classes >= 0]  # Пиксели внутри области.
    # Строка таблицы на каждый класс: доля пикселей, %.
    table = [{"класс": c, "доля, %": round(100 * float(np.mean(inside == k)), 1)} for k, c in enumerate(card["classes"])]
    top = max(table, key=lambda r: r["доля, %"])  # Класс с наибольшей долей.
    share = f"{top['доля, %']:.1f}".replace(".", ",")  # Десятичная запятая.
    return {"name": NAME, "table": table, "text": f"Преобладает класс «{top['класс']}»: {share} % площади"}  # Таблица и вывод.
